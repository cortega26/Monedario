const BUILD_DEV_PAGES = process.env.BUILD_DEV_PAGES === "1";
type AstroConfigSetupOptions = Parameters<
  NonNullable<AstroIntegration["hooks"]["astro:config:setup"]>
>[0];

function shouldEnableDevPages(command: AstroConfigSetupOptions["command"]) {
  return command !== "build" || BUILD_DEV_PAGES;
}

function devPagesIntegration(): AstroIntegration {
  const reactIntegration = react();

  return {
    name: "monedario-dev-pages",
    hooks: {
      "astro:config:setup": async options => {
        if (!shouldEnableDevPages(options.command)) return;

        await reactIntegration.hooks["astro:config:setup"]?.(options);

        options.injectRoute({
          pattern: "/dev/hero-images",
          entrypoint: "./src/dev-pages/hero-images.astro",
        });
      },
    },
  };
}

// ── Sitemap lastmod: load article dates ───────────────────────────────────
type ArticleIndex = { slug: string; updatedDate?: string };
const articleDateMap = new Map<string, string>();
try {
  const indexData = JSON.parse(
    readFileSync("./context/published-articles-index.json", "utf-8")
  ) as { articles?: ArticleIndex[] };
  if (indexData.articles) {
    for (const article of indexData.articles) {
      const dateStr = article.updatedDate?.split("T")[0];
      if (dateStr) {
        articleDateMap.set(`/posts/${article.slug}/`, dateStr);
      }
    }
  }
} catch {
  // Non-blocking — sitemap works without lastmod
}

// Static-page lastmod (calculators, guide hubs, standalone pages). Generated
// by scripts/build-page-lastmod.mjs from git history; see that script for why
// it is a committed index rather than read live at build time.
const pageLastmodMap = new Map<string, string>();
try {
  const pageIndex = JSON.parse(
    readFileSync("./context/page-lastmod-index.json", "utf-8")
  ) as { pages?: Record<string, string> };
  for (const [pathname, date] of Object.entries(pageIndex.pages ?? {})) {
    pageLastmodMap.set(pathname, date);
  }
} catch {
  // Non-blocking — sitemap works without page lastmod
}
