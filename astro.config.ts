const tocUi = getUiCopyForLocale(SITE.lang);

function escapeRegExp(value: string) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function safeRegExp(pattern: string, flags = "i", maxLength = 256) {
  if (pattern.length > maxLength) {
    throw new Error(`RegExp pattern too long: ${pattern.slice(0, 32)}...`);
  }
  return new RegExp(pattern, flags);
}
const tocHeadingPattern = tocUi.toc.title;

type RemarkTextNode = {
  type: string;
  value?: string;
};

type RemarkBlockNode = {
  type: string;
  children?: RemarkTextNode[];
};

type RemarkRoot = {
  children: RemarkBlockNode[];
};

// Removes the in-body "Tabla de contenidos" heading (and any immediately
// following list node generated by a prior remarkToc pass) from the MDAST.
// This avoids duplicating the sidebar TOC that TOCSidebar.astro renders.
function remarkStripTocSection() {
  return (tree: RemarkRoot) => {
    const children = tree.children;
    let i = 0;
    while (i < children.length) {
      const node = children[i];
      const isMatchingHeading =
        node.type === "heading" &&
        node.children?.some(
          c => c.type === "text" && c.value === tocHeadingPattern
        );
      if (isMatchingHeading) {
        const followingIsListOrParagraph =
          children[i + 1]?.type === "list" ||
          children[i + 1]?.type === "paragraph";
        children.splice(i, followingIsListOrParagraph ? 2 : 1);
      } else {
        i++;
      }
    }
  };
}
const SITE_BASE = new URL(SITE.website).pathname.replace(/\/$/, "") || "/";
const HOME_PATH = SITE_BASE === "/" ? "/" : `${SITE_BASE}/`;
const withBasePath = (path: string) =>
  SITE_BASE === "/" ? path : `${SITE_BASE}${path}`;
const SITEMAP_EXCLUDED_PATHS = new Set([
  withBasePath("/posts/interes-compuesto-nota-metodologica/"),
]);
const TAGS_ROOT_PATH = withBasePath("/tags/");
const SEARCH_PATH = withBasePath("/search/");
const BUSCAR_PATH = withBasePath("/buscar/");
const PAGINATED_POSTS_PATTERN = safeRegExp(
  `^${escapeRegExp(withBasePath("/posts/"))}\\d+/$`
);
